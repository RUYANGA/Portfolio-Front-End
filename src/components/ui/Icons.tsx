/** Picks an icon for a social link from its label or URL. */
export function SocialIcon({ label, url, size }: { label: string; url: string; size?: number }) {
  const key = `${label} ${url}`.toLowerCase();
  if (key.includes("github")) return <GitHub size={size} />;
  if (key.includes("linkedin")) return <LinkedIn size={size} />;
  if (key.includes("mailto") || key.includes("email")) return <Mail size={size} />;
  if (key.includes("tel:") || key.includes("phone")) return <Phone size={size} />;
  return <ArrowUpRight size={size} />;
}

/** Picks an icon for a skill group from its name. */
export function SkillIcon({ name, size }: { name: string; size?: number }) {
  const key = name.toLowerCase();
  if (/(secur|auth)/.test(key)) return <Shield size={size} />;
  if (/(\bai\b|stream|kafka|event|ml)/.test(key)) return <Zap size={size} />;
  if (/(database|sql|cach|storage)/.test(key)) return <Database size={size} />;
  if (/(cloud|devops|aws|infra|deploy)/.test(key)) return <Cloud size={size} />;
  if (/(front|mobile|ui|web)/.test(key)) return <Layers size={size} />;
  if (/(back|api|server|framework)/.test(key)) return <Server size={size} />;
  if (/(tool|practice|test)/.test(key)) return <Wrench size={size} />;
  return <Code size={size} />;
}

